#!/usr/bin/env python3
"""
Run every check and write docs/VERIFICATION.md (numbers are generated, not typed).

    python cad/verify_all.py
"""
import datetime
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from deskgen import params as P                                   # noqa: E402
from deskgen import analysis as A                                 # noqa: E402
from deskgen.design import Design                                 # noqa: E402
from deskgen.mesh import to_trimesh                               # noqa: E402
from deskgen.kit import build_kit_meshes, to_print_pose, NICE_NAMES, shell_support  # noqa: E402
from deskgen.verify import mesh_health, printability, wall_thickness, interference, min_gap  # noqa: E402

PLA = 1.24   # g/cm3


def md_table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    L = []
    w = L.append
    w("# Verification report")
    w("")
    w(f"Generated by `cad/verify_all.py` on {datetime.date.today().isoformat()}. "
      "Every number below is computed from the same geometry that produced the print files.")
    w("")

    # ------------------------------------------------------------ print kit
    dk, K = build_kit_meshes()
    w("## 1. Print kit (1:6)")
    w("")
    rows, total_g = [], 0.0
    import trimesh
    for n, m in K.items():
        h = mesh_health(m)
        # the shell is checked as printed, with its breakaway support fin
        p = to_print_pose(n, trimesh.util.concatenate([m] + shell_support(dk)) if n == "shell" else m)
        pr = printability(p)
        wt = wall_thickness(p, n=2500)
        g = h["volume_mm3"] / 1000 * PLA
        total_g += g
        worst = pr["overhang_clusters"][0] if pr["overhang_clusters"] else None
        rows.append([NICE_NAMES[n], "yes" if h["watertight"] and h["winding"] else "NO",
                     " x ".join(f"{v:.0f}" for v in pr["extents_mm"]), f"{g:.1f} g",
                     f"{pr['bed_contact_mm2']:.0f}", f"{wt['p5']:.2f}",
                     (f"{worst['area_mm2']:.0f} mm2, {worst['span_mm']:.0f} mm span" if worst else "none")])
    w(md_table(["part", "watertight", "print size (mm)", "solid PLA", "bed contact (mm2)",
                "5th pct wall (mm)", "largest >45 deg overhang region"], rows))
    w("")
    w(f"Total solid PLA: about {total_g:.0f} g (a real print with 15-20% infill uses less).")
    w("")
    w("How to read the overhang column: what is left is (a) the undersides of small edge fillets right at the bed "
      "(they start within half a millimetre of it and print as part of the first layers), (b) flat bridges of about "
      "10 mm or less: the tab sockets in the seat and the pencil groove, which prints face down, and (c) on the seat "
      "shell, the underside of its side roll along the bed, up to 6 mm above it at about 65 degrees, which comes out "
      "slightly rough. The one stretch that would otherwise hang in the air, the lower edge of the back's waist, "
      "prints on a breakaway fin that is part of the shell's file. No slicer supports are needed.")
    w("")
    inter = interference(K)
    w(f"**Assembly interference (parts overlapping each other when assembled):** "
      f"{'none' if not inter else inter}")
    w("")
    w("**Clearances at the joints** (closest surface-to-surface distance, assembled; 0 means the faces touch):")
    w("")
    pairs = [("frame_L", "shell", "frame tab in seat socket"), ("frame_L", "base", "frame on cross-bar tab"),
             ("sleeve", "base", "sleeve in T-foot socket"), ("head", "sleeve", "post in sleeve"),
             ("head", "top", "dovetail in track"), ("plug", "top", "end plug in track")]
    w(md_table(["joint", "gap (mm)"], [[lab, f"{min_gap(K[a], K[b]):.2f}"] for a, b, lab in pairs]))
    w("")
    w("**Pin alignment (geometry probe along each pin axis):**")
    w("")
    pa = A.pin_alignment(dk)
    w(md_table(["pin", "setting", "clear through all parts"],
               [[r["check"], r["setting"], "yes" if all(v for k, v in r.items() if k.startswith("passes")) else "NO"]
                for r in pa]))
    w("")
    kp = dk.kit
    w("**Fits (per side clearance):** sliding joints (post in sleeve, dovetail) "
      f"{kp['slide']} mm; press joints (frame tabs in seat pads, cross-bar tabs, sleeve in T-foot, end plug) "
      f"{kp['snug']} mm. Pins: {kp['pin_d']} mm filament; free holes {kp['pin_hole']} mm, the sleeve's hole "
      f"{kp['pin_grip']} mm (grips the height pin) and the head's guide {kp['pin_guide']} mm (holds the reach pin "
      "by friction so it can't drop out).")
    w("")
    gk = dk.g
    xa = dk.outline.apex_centre[0]
    w("**Flexing back on the model** (1-D beam along the shell, PLA E = 3.2 GPa, push at shoulder-blade height):")
    w("")
    rows = []
    for F in (2, 5, 10, 20):
        r = A.back_flex(gk, 3200, F, (P.SEAT_HEIGHT + 340) * dk.k, gk.s_at_x(xa - 70 * dk.k))
        rows.append([f"{F} N", f"{r['rotation_deg']:.1f} deg", f"{r['deflection_mm']:.1f} mm", f"{r['peak_strain_pct']:.2f} %"])
    w(md_table(["finger push", "back tilts", "top moves", "peak strain"], rows))
    w("")
    w("PLA tolerates roughly 1.5-2 % strain for repeated flexing, so a firm push (10-20 N) is safe. "
      "The shell prints on its side so the bending runs along the printed lines, not across layer joints.")
    w("")

    # ------------------------------------------------------------ full size
    d = Design("real", ribs=True)
    M = {"shell": d.shell_mesh()}
    for n, f in [("seat_beam", d.seat_beam), ("frame_L", lambda: d.frame(+1)), ("frame_R", lambda: d.frame(-1)),
                 ("base", d.base), ("sleeve", d.sleeve), ("head", d.head), ("top", d.top), ("plug", d.plug)]:
        M[n] = to_trimesh(f(), 0.3, 0.2)
    w("## 2. Full-size product")
    w("")
    rows, mass, cog = A.mass_properties(M)
    w(md_table(["part", "volume (L)", "effective density", "mass (kg)", "basis"],
               [[NICE_NAMES[r["part"]], f"{r['volume_L']:.2f}", r["density"], f"{r['mass_kg']:.2f}", r["note"]]
                for r in rows]))
    w("")
    w(f"**Total about {mass:.1f} kg ({mass * 2.2046:.0f} lb)**, centre of gravity at X = {cog[0]:.0f} mm, "
      f"Z = {cog[2]:.0f} mm. For comparison the Virco 3700BRM is listed at 35-45 lb.")
    w("")
    ri = interference(M)
    w(f"**Assembly interference (full size):** {'none' if not ri else ri}")
    w("")
    poly = A.support_polygon(M)
    W = mass * A.G
    Z = P.SEAT_HEIGHT
    w("### Tipping (rigid-body statics about the edges of the floor footprint)")
    w("")
    Hreq = 1.1 * (47 - P.SEAT_HEIGHT / 25.4) * 4.448
    H1 = A.max_load_before_tip(poly, W, cog, [(0, 0, -800, 175, 0, Z)], (-1, 0, 0, -90, 0, 850))
    r2 = A.tip_margin(poly, W, cog, [(0, 0, -1780, 110, 0, Z), (-250, 0, 0, -90, 0, 800)])[0]
    def tips(v):
        return "does not tip" if v >= 19999 else f"tips at {v / 9.81:.0f} kg"

    rows = [["Rear: 81.6 kg on the seat + push backward at the top of the back (BIFMA-style)",
             f"tips at {H1:.0f} N", f"needs {Hreq:.0f} N (X5.1 formula)", "PASS" if H1 > Hreq else "FAIL"],
            ["Rear: 181 kg (400 lb) student leaning back + 250 N push with the feet",
             f"margin {r2:.2f}", "> 1.0", "PASS" if r2 > 1 else "FAIL"]]
    xb, zb_ = P.SHELL_PATH[-2]
    wb = A.max_load_before_tip(poly, W, cog, [], (0, 0, -1, xb, 0, zb_))
    rows.append(["Rear: empty chair, someone presses straight down on the top of the backrest", tips(wb),
                 "> 50 kg", "PASS" if wb / 9.81 > 50 else "CHECK"])
    # the desk's position moves the centre of gravity, so each reach setting is checked with its own geometry
    worst_near = 1e9
    for gi in range(len(P.DESK_GAPS)):
        Mg = dict(M)
        Mg["top"] = to_trimesh(d.top(P.DEFAULT_HEIGHT_INDEX, gi), 0.3, 0.2)
        Mg["plug"] = to_trimesh(d.plug(P.DEFAULT_HEIGHT_INDEX, gi), 0.3, 0.2)
        _, mg, cg = A.mass_properties(Mg)
        far = P.desk_near_x(gi) + P.TOP_D
        wc = A.max_load_before_tip(poly, mg * A.G, cg, [], (0, 0, -1, far - 40, P.TOP_W / 2 - 40, P.DESK_HEIGHTS[3]))
        rows.append([f"Forward: someone sits on the far desk corner, empty seat, reach {P.DESK_GAPS[gi]:.0f}",
                     tips(wc), "> 100 kg", "PASS" if wc / 9.81 > 100 else "CHECK"])
        worst_near = min(worst_near, A.max_load_before_tip(
            poly, mg * A.G, cg, [], (0, 0, -1, P.desk_near_x(gi) + 30, P.TOP_W_NEAR / 2 - 30, 730)))
    rows.append(["Sideways: leaning on the near desk corner, empty seat (worst reach)", tips(worst_near),
                 "> 100 kg", "PASS" if worst_near / 9.81 > 100 else "CHECK"])
    ws = A.max_load_before_tip(poly, W, cog, [], (0, 0, -1, 200, P.SEAT_WIDTH / 2 - 5, Z))
    rows.append(["Sideways: sitting on the very edge of the seat", tips(ws), "-", "PASS" if ws / 9.81 > 100 else "CHECK"])
    ren = A.tip_margin(poly, W, cog, [(0, 0, -600, 200, P.SEAT_WIDTH / 2 - 20, Z), (0, 20, 0, 200, P.SEAT_WIDTH / 2 - 20, Z)])[0]
    rows.append(["Sideways: 600 N down near the seat's side edge + 20 N outward (the EN 1022 sideways test loads)",
                 f"margin {ren:.1f}", "> 1.0", "PASS" if ren > 1 else "FAIL"])
    worst_lean = min(A.tip_margin(poly, W, cog, [
        (0, 0, -kg * A.G * 0.65, 200, P.SEAT_WIDTH / 2 - 40, Z),            # hips slid to the edge
        (0, 0, -kg * A.G * 0.25, 180, P.SEAT_WIDTH / 2 + 200, Z + 250),     # torso hanging 20 cm past the edge
        (0, 20, 0, 200, P.SEAT_WIDTH / 2, Z)])[0] for kg in (80, 100, 140, 181))
    rows.append(["Sideways: student leans out to pick a bag off the floor (80-181 kg, feet lifted, worst case)",
                 f"margin {worst_lean:.2f}", "> 1.0", "PASS" if worst_lean > 1 else "FAIL"])
    w(md_table(["load case", "result", "target", ""], rows))
    w("")
    w("\"Feet lifted\" in the last row means the student's whole weight is on the chair, which is the worst case; "
      "in practice a foot on the floor takes part of it. The glide pods on the outside of each frame's feet widen the "
      f"footprint to {2 * (P.FRAME_Y_OUT + P.POD_OUT):.0f} mm at the seat, which is what keeps the sideways cases safe.")
    w("")
    w("### Strength (hand calculations)")
    w("")
    xr = d.outline.apex_centre[0]            # full-size apex position
    ps = A.post_stress(1000, P.POST_X - P.desk_near_x(0))
    sp = A.seat_pan_stress(d.g, 1000, 400, xr + 50)
    g = d.g
    rows = [["Post: 100 kg on the near desk edge, nearest reach", f"{ps['moment_Nm']:.0f} N m",
             f"sleeve {ps['sleeve_stress_MPa']} MPa, inner {ps['inner_stress_MPa']} MPa", "6063-T6 yield 214 MPa"],
            ["Seat front: 1000 N on the front edge", f"{sp['moment_Nm']:.0f} N m", f"{sp['stress_MPa']:.1f} MPa",
             "PP copolymer yield ~25-30 MPa"]]
    for F, label in ((150, "casual lean"), (250, "firm lean"), (1000, "BIFMA X6.1 back functional load")):
        r = A.back_flex(g, 1300, F, P.SEAT_HEIGHT + 340, g.s_at_x(xr - 70))
        rows.append([f"Back: {F} N at shoulder-blade height ({label})", f"back tilts {r['rotation_deg']:.1f} deg",
                     f"{r['peak_stress_MPa']:.1f} MPa at Z={r['peak_at_z_mm']:.0f}", "PP E = 1.3 GPa (linear model)"])
    w(md_table(["case", "load", "result", "reference"], rows))
    w("")
    w("The backrest is designed to give a few degrees under a casual lean and about twice that under a firm one. "
      "Under the 1000 N BIFMA back test, the linear estimate exceeds the yield strength of unfilled "
      "polypropylene, so a production shell should use a 20 % talc- or glass-filled PP in the junction (or be tuned "
      "with FEA) and be proven by a physical BIFMA X6.1 test. This is normal for moulded school chairs.")
    w("")
    w("### Ergonomic fit (ANSUR II adult data as the proxy for high-schoolers; see RESEARCH.md)")
    w("")
    rows = []
    for r in A.ergonomics():
        fr = r["with_spine_footrest_mm"]
        rows.append([r["who"], f"{r['seat_vs_popliteal_mm']:+.0f} mm" + (f" ({fr:+.0f} on the spine)" if fr is not None else ""),
                     f"{r['seat_depth_pct_bpl']:.0f} %", f"{r['hip_room_mm']:+.0f} mm",
                     f"{r['best_desk_height']:.0f} mm", ", ".join(f"{h:.0f}" for h in r["desk_heights_with_thigh_room"]),
                     r["reach_setting"]])
    w("The reach setting is the first one that leaves 3 cm between belly and desk, measured at the middle of the "
      "desk's curved near edge.")
    w("")
    w(md_table(["student", "seat height vs knee height (+ = too high)", "seat depth / thigh length",
                "seat width vs hips", "best desk height", "desk heights with thigh room", "reach setting"], rows))
    w("")
    w("Reading the table: seat depth should stay under 95 % of thigh length (it does for everyone). A seat that is "
      "too high presses on the underside of the thigh; the 5th percentile student rests her feet on the 42 mm spine "
      "and the mismatch drops to about 1 cm. Larger-bodied students are wider than any school seat; the open sides "
      "(no side bar, no arms) let them sit comfortably anyway.")
    w("")
    w("## 3. Known limitations")
    w("")
    w("- Anthropometry uses adult US Army data (ANSUR II) as a stand-in; the new YouthShape.US teen survey was not "
      "published yet.")
    w("- Strength and stiffness numbers come from hand calculations (1-D beams, rigid-body tipping), not FEA. "
      "They are good for catching bad ideas early, not for certifying a product.")
    w("- The PLA model is a demonstration: it flexes, slides and adjusts like the real design, but PLA fatigues "
      "much sooner than polypropylene.")
    path = os.path.join(ROOT, "docs", "VERIFICATION.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("\n".join(L) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
